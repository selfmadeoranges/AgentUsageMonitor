import json
from pathlib import Path

try:
    Import("env")
    project_dir = Path(env["PROJECT_DIR"])
except NameError:
    project_dir = Path(__file__).resolve().parents[1]

repository_dir = project_dir.parents[1]
source_path = repository_dir / "shared" / "smalltv-display-layout.json"
output_path = project_dir / "include" / "GeneratedDisplayLayout.h"


def value(document, *path):
    current = document
    for part in path:
        current = current[part]
    return current


def color(document, name):
    return int(value(document, "colors", name), 0)


def cpp_string(text):
    return json.dumps(text, ensure_ascii=True)


def generate_header(document):
    if value(document, "schemaVersion") != 1:
        raise ValueError("Unsupported SmallTV display layout schema")
    if value(document, "display", "width") != 240 or value(document, "display", "height") != 240:
        raise ValueError("SmallTV-Ultra display must remain 240 x 240")
    if not 1 <= value(document, "usagePage", "row", "count") <= 3:
        raise ValueError("Usage row count must be between 1 and 3")

    constants = [
        ("uint16_t", "Width", value(document, "display", "width")),
        ("uint16_t", "Height", value(document, "display", "height")),
        ("uint32_t", "PageIntervalMs", value(document, "display", "pageIntervalMs")),
        ("uint16_t", "BackgroundColor", f"0x{color(document, 'background'):04X}"),
        ("uint16_t", "PanelColor", f"0x{color(document, 'panel'):04X}"),
        ("uint16_t", "MutedColor", f"0x{color(document, 'muted'):04X}"),
        ("uint16_t", "GreenColor", f"0x{color(document, 'green'):04X}"),
        ("uint16_t", "OrangeColor", f"0x{color(document, 'orange'):04X}"),
        ("uint16_t", "RedColor", f"0x{color(document, 'red'):04X}"),
    ]

    numeric_paths = {
        "UsageTitle": ("usagePage", "title", ["x", "y", "font", "scale"]),
        "UsageCounter": ("usagePage", "counter", ["x", "y", "font", "scale"]),
        "UsageRow": ("usagePage", "row", [
            "x", "y", "width", "height", "step", "count", "labelX", "labelOffsetY", "labelFont",
            "percentRight", "percentOffsetY", "percentFont", "barX", "barOffsetY", "barWidth", "barHeight",
            "countdownX", "countdownOffsetY", "countdownFont"
        ]),
        "UsageEmpty": ("usagePage", "empty", ["x", "y", "font", "scale"]),
        "UsageFooter": ("usagePage", "footer", [
            "x", "y", "width", "height", "stateX", "stateY", "stateFont", "ipX", "ipY", "ipFont"
        ]),
    }
    for prefix, (section, item, names) in numeric_paths.items():
        for name in names:
            constants.append(("int16_t", prefix + name[0].upper() + name[1:], value(document, section, item, name)))

    recovery_items = ["title", "connectLabel", "ssid", "passwordLabel", "password", "openAddress", "user"]
    for item in recovery_items:
        prefix = "Recovery" + item[0].upper() + item[1:]
        for name in ["x", "y", "font", "scale"]:
            constants.append(("int16_t", prefix + name[0].upper() + name[1:], value(document, "recoveryPage", item, name)))

    lines = [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// Generated from shared/smalltv-display-layout.json. Do not edit this file.",
        "namespace DisplayLayout {",
    ]
    for cpp_type, name, item_value in constants:
        lines.append(f"constexpr {cpp_type} {name} = {item_value};")

    for item in ["title", "connectLabel", "passwordLabel", "openAddress", "user"]:
        name = "Recovery" + item[0].upper() + item[1:] + "Text"
        lines.append(f"constexpr char {name}[] = {cpp_string(value(document, 'recoveryPage', item, 'text'))};")

    text_names = {
        "usageUnavailable": "UsageUnavailableText",
        "synchronizingTime": "SynchronizingTimeText",
        "configureAccount": "ConfigureAccountText",
        "refreshFailed": "RefreshFailedText",
        "loadingUsage": "LoadingUsageText",
        "retryingLater": "RetryingLaterText",
        "stateStale": "StateStaleText",
        "stateRateLimited": "StateRateLimitedText",
        "stateAuthRequired": "StateAuthRequiredText",
        "stateRefreshFailed": "StateRefreshFailedText",
        "stateNetworkError": "StateNetworkErrorText",
        "stateInvalidResponse": "StateInvalidResponseText",
        "ipPrefix": "IpPrefixText",
    }
    for source_name, cpp_name in text_names.items():
        lines.append(f"constexpr char {cpp_name}[] = {cpp_string(value(document, 'text', source_name))};")

    lines.extend(["}", ""])
    return "\n".join(lines)


with source_path.open("r", encoding="utf-8") as source_file:
    layout = json.load(source_file)

generated = generate_header(layout)
previous = output_path.read_text(encoding="utf-8") if output_path.exists() else None
if generated != previous:
    output_path.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Generated {output_path} from {source_path}")
